#!/usr/bin/env python3

def mkstr(element: str) -> str:
    return f"{element} element created"


def create_fire() -> str:
    return mkstr("Fire")


def create_water() -> str:
    return mkstr("Water")


def create_earth() -> str:
    return mkstr("Earth")


def create_air() -> str:
    return mkstr("Air")
